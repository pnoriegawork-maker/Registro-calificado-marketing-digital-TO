window.showC2Section = function(targetId) {
    const panels = ['c2-eje-1', 'c2-eje-2', 'c2-eje-3', 'c2-eje-4', 'c2-eje-5', 'c2-eje-6', 'c2-eje-7'];
    panels.forEach(id => {
        const el = document.getElementById(id);
        if (el) el.style.display = (id === targetId) ? 'block' : 'none';
    });
    const bar = document.getElementById('c2-subtabs-bar');
    if (bar) {
        bar.querySelectorAll('.c2-subtab-btn').forEach(btn => {
            const isTarget = btn.getAttribute('data-c2-target') === targetId;
            if (isTarget) {
                btn.style.background = '#1A1A1B';
                btn.style.color = '#FFFFFF';
                btn.style.border = '1.5px solid #F39200';
                btn.style.fontWeight = '800';
                btn.style.boxShadow = '0 2px 8px rgba(243,146,0,0.25)';
            } else {
                btn.style.background = '#F8FAFC';
                btn.style.color = '#334155';
                btn.style.border = '1px solid #CBD5E1';
                btn.style.fontWeight = '700';
                btn.style.boxShadow = 'none';
            }
        });
    }
    if (targetId === 'c2-eje-3') {
        setTimeout(() => window.initMktLeafletMap(), 120);
    }
    if (targetId === 'c2-eje-5') {
        setTimeout(() => window.initMktC2Charts(), 120);
    }
};

